import type { BomItemDetail } from '../Types/bom'
import { isAutoGeneratedPartNumber, iplDisplayPartNumber } from './iplModelParts'
import {
  comparePartNumbers,
  compareQuantities,
  compareStations,
  type FieldCompareResult,
  type IplCompareRow
} from './iplModelCompare'
import { bomRowAssignedToIplModel, iplFitStatusForModel, isIplCompareFitToken } from './iplFitStatus'
import { normalizePartNumber } from './partNumberNormalize'

function pickBestItem(items: BomItemDetail[], model: string): BomItemDetail {
  if (items.length === 1) return items[0]
  return [...items].sort((a, b) => {
    const fitRank = (x: BomItemDetail) => {
      const status = iplFitStatusForModel(x, model)
      if (status === 'fitted') return 0
      if (status === 'not_fitted') return 1
      return 2
    }
    const fitDiff = fitRank(a) - fitRank(b)
    if (fitDiff !== 0) return fitDiff
    const autoDiff =
      (isAutoGeneratedPartNumber(a.part_number) ? 1 : 0) - (isAutoGeneratedPartNumber(b.part_number) ? 1 : 0)
    if (autoDiff !== 0) return autoDiff
    return (iplDisplayPartNumber(b.part_number) ? 1 : 0) - (iplDisplayPartNumber(a.part_number) ? 1 : 0)
  })[0]
}

export function buildOperationCompareRow(
  partId: string,
  models: string[],
  bomRows: BomItemDetail[]
): IplCompareRow | null {
  if (!partId || models.length === 0) return null
  const byModel = new Map<string, BomItemDetail>()
  let partNameAr = '—'
  let partNameEn = '—'
  for (const model of models) {
    const candidates = bomRows.filter(row => row.part_id === partId && bomRowAssignedToIplModel(row, model))
    if (candidates.length === 0) continue
    const best = pickBestItem(candidates, model)
    byModel.set(model, best)
    partNameAr = best.part_name_ar ?? best.part_name ?? partNameAr
    partNameEn = best.part_name_en ?? partNameEn
  }
  if (byModel.size === 0) return null
  return { key: partId, partNameAr, partNameEn, byModel }
}

export type OperationClassCompare = {
  overall: 'shared' | 'different' | 'missing'
  partNumber: FieldCompareResult
  station: FieldCompareResult
  quantity: FieldCompareResult
}

export function classifyOperationCompare(row: IplCompareRow, models: string[]): OperationClassCompare {
  const partNumber = comparePartNumbers(row, models)
  const station = compareStations(row, models)
  const quantity = compareQuantities(row, models)
  const statuses = [partNumber.status, station.status, quantity.status]
  if (statuses.every(status => status === 'missing')) {
    return { overall: 'missing', partNumber, station, quantity }
  }
  if (statuses.some(status => status === 'different')) {
    return { overall: 'different', partNumber, station, quantity }
  }
  return { overall: 'shared', partNumber, station, quantity }
}

export function hardwareTotalQty(hardware: { hardwareQty: number | null }[]): number {
  if (hardware.length === 0) return 0
  return hardware.reduce((sum, item) => sum + (item.hardwareQty != null && Number.isFinite(item.hardwareQty) ? item.hardwareQty : 1), 0)
}

export function hardwareCompareMode(hardware: { hardwareName: string }[]): 'shared' | 'different' | 'missing' {
  if (hardware.length === 0) return 'missing'
  const numbers = new Set(hardware.map(item => item.hardwareName.trim().toUpperCase()).filter(Boolean))
  return numbers.size <= 1 ? 'shared' : 'different'
}

export type HardwareIplCompare = {
  mode: 'shared' | 'different' | 'missing'
  qtyLabel: string
  compare: OperationClassCompare | null
  titleName: string
}

function bomRowsForHardwareItem(
  item: { hardwareName: string; hardwareSize: string | null },
  bomRows: BomItemDetail[]
): BomItemDetail[] {
  const numberKey = normalizePartNumber(item.hardwareName)
  const nameKey = (item.hardwareSize ?? '').trim().toLowerCase()
  const direct = bomRows.filter(row => {
    const rowNumber = normalizePartNumber(row.part_number ?? '')
    const rowName = (row.part_name_ar ?? row.part_name ?? '').trim().toLowerCase()
    if (numberKey && rowNumber && rowNumber === numberKey) return true
    if (nameKey && rowName && rowName === nameKey) return true
    return false
  })
  if (direct.length === 0) return []
  const names = new Set(
    direct.map(row => (row.part_name_ar ?? row.part_name ?? '').trim().toLowerCase()).filter(Boolean)
  )
  if (names.size === 0) return direct
  return bomRows.filter(row => names.has((row.part_name_ar ?? row.part_name ?? '').trim().toLowerCase()))
}

function buildCompareRowFromBom(bomRows: BomItemDetail[], models: string[]): IplCompareRow | null {
  if (bomRows.length === 0 || models.length === 0) return null
  const byModel = new Map<string, BomItemDetail>()
  let partNameAr = bomRows[0]?.part_name_ar ?? bomRows[0]?.part_name ?? '—'
  let partNameEn = bomRows[0]?.part_name_en ?? '—'
  for (const model of models) {
    const candidates = bomRows.filter(row => bomRowAssignedToIplModel(row, model))
    if (candidates.length === 0) continue
    const best = pickBestItem(candidates, model)
    byModel.set(model, best)
    partNameAr = best.part_name_ar ?? best.part_name ?? partNameAr
    partNameEn = best.part_name_en ?? partNameEn
  }
  if (byModel.size === 0) return null
  return { key: partNameAr, partNameAr, partNameEn, byModel }
}

function qtyLabelFromCompare(quantity: FieldCompareResult, fallback: number): string {
  if (quantity.status === 'same' && quantity.sharedValue && !isIplCompareFitToken(quantity.sharedValue)) {
    return quantity.sharedValue
  }
  if (quantity.status === 'different') {
    const values = [
      ...new Set(
        quantity.byModel
          .map(entry => entry.value.trim())
          .filter(value => value && value !== '—' && !isIplCompareFitToken(value))
      )
    ].sort((a, b) => Number(a) - Number(b) || a.localeCompare(b))
    if (values.length > 0) return values.join('/')
  }
  return String(fallback > 0 ? fallback : 1)
}

/** Classify linked hardware from IPL BOM across selected models (number + qty). */
export function classifyHardwareFromIpl(
  hardware: { hardwareName: string; hardwareSize: string | null; hardwareQty: number | null }[],
  models: string[],
  bomRows: BomItemDetail[]
): HardwareIplCompare {
  if (hardware.length === 0) {
    return { mode: 'missing', qtyLabel: '0', compare: null, titleName: '' }
  }

  const matchedRows = hardware.flatMap(item => bomRowsForHardwareItem(item, bomRows))
  const compareRow = buildCompareRowFromBom(matchedRows, models)
  if (!compareRow) {
    const fallbackMode = hardwareCompareMode(hardware)
    return {
      mode: fallbackMode,
      qtyLabel: String(hardwareTotalQty(hardware) || 1),
      compare: null,
      titleName: hardware[0]?.hardwareSize || hardware[0]?.hardwareName || ''
    }
  }

  const compare = classifyOperationCompare(compareRow, models)
  return {
    mode: compare.overall === 'missing' ? hardwareCompareMode(hardware) : compare.overall,
    qtyLabel: qtyLabelFromCompare(compare.quantity, hardwareTotalQty(hardware)),
    compare,
    titleName: compareRow.partNameAr
  }
}
