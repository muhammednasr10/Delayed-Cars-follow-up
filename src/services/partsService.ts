export type PartsListFilters = {
  search?: string
  modelName?: string
  stationCode?: string
  page?: number
  pageSize?: number
}

export async function listPartsForIplModel(
  filters: PartsListFilters & { modelName: string }
): Promise<{ items: PartListRow[]; total: number }> {
  const modelName = filters.modelName.trim()
  if (!modelName) return { items: [], total: 0 }

  const page = filters.page ?? 1
  const pageSize = filters.pageSize ?? 100

  let q = client()
    .from('parts')
    .select('*')
    .eq('is_active', true)
    .order('common_station', { ascending: true, nullsFirst: false })
    .order('common_name', { ascending: true, nullsFirst: false })
    .order('part_name_ar', { ascending: true })
    .limit(5000)

  const search = filters.search?.trim()
  if (search) {
    const s = search.replace(/%/g, '\\%')
    q = q.or(
      `common_station.ilike.%${s}%,common_name.ilike.%${s}%,part_name_ar.ilike.%${s}%,part_name_en.ilike.%${s}%,part_number.ilike.%${s}%`
    )
  }

  const { data, error } = await q
  if (error) throw new Error(error.message)

  let parts = dedupePartListRows(((data ?? []) as Part[]).filter(p => partMatchesIplModel(p, modelName)))

  const stationCode = filters.stationCode?.trim()
  if (stationCode) {
    const code = stationCode.toUpperCase()
    parts = parts.filter(p => (p.common_station ?? '').trim().toUpperCase() === code)
  }

  const total = parts.length
  const from = (page - 1) * pageSize
  const pageItems = parts.slice(from, from + pageSize).map(p => ({ ...p }))

  return { items: pageItems, total }
}

export type PartMasterHit = {
  id: string
  part_number: string
  part_name_ar: string | null
  part_name_en: string | null
  common_name: string | null
  common_station: string | null
  part_type: string | null
  common_supply_source: string | null
}

export async function searchPartsMaster(term: string, limit = 15): Promise<PartMasterHit[]> {
  const q = term.trim().replace(/%/g, '\\%')
  if (!q) return []

  const { data, error } = await client()
    .from('parts')
    .select(
      'id, part_number, part_name_ar, part_name_en, common_name, common_station, part_type, common_supply_source'
    )
    .eq('is_active', true)
    .or(
      `part_name_ar.ilike.%${q}%,part_name_en.ilike.%${q}%,common_name.ilike.%${q}%,common_station.ilike.%${q}%`
    )
    .order('common_name', { ascending: true, nullsFirst: false })
    .order('part_name_ar', { ascending: true })
    .limit(limit)

  if (error) throw new Error(error.message)
  const hits = (data ?? []) as PartMasterHit[]
  const byKey = new Map<string, PartMasterHit>()
  for (const hit of hits) {
    const key = partListMasterKey({
      id: hit.id,
      part_name_ar: hit.part_name_ar,
      part_name_en: hit.part_name_en,
      common_name: hit.common_name
    })
    const prev = byKey.get(key)
    if (!prev || scorePartMasterRow(hit as Part) > scorePartMasterRow(prev as Part)) {
      byKey.set(key, hit)
    }
  }
  return [...byKey.values()]
}

async function countModelsByPartIds(partIds: string[]): Promise<Map<string, Array<{
  qty_by_model_raw: string | null
  applicable_models_text: string | null
  vehicle_model_name: string | null
  quantity: number | null
}>>> {
  const rowsByPart = new Map<string, Array<{
    qty_by_model_raw: string | null
    applicable_models_text: string | null
    vehicle_model_name: string | null
    quantity: number | null
  }>>()
  if (partIds.length === 0) return rowsByPart

  const CHUNK = 100
  for (let i = 0; i < partIds.length; i += CHUNK) {
    const chunk = partIds.slice(i, i + CHUNK)
    const { data, error } = await client()
      .from('v_bom_items_detail')
      .select('part_id, qty_by_model_raw, applicable_models_text, vehicle_model_name, quantity')
      .eq('is_active', true)
      .in('part_id', chunk)
    if (error) throw new Error(error.message)
    for (const row of data ?? []) {
      const pid = row.part_id as string
      const bucket = rowsByPart.get(pid) ?? []
      bucket.push({
        qty_by_model_raw: row.qty_by_model_raw as string | null,
        applicable_models_text: row.applicable_models_text as string | null,
        vehicle_model_name: row.vehicle_model_name as string | null,
        quantity: row.quantity as number | null
      })
      rowsByPart.set(pid, bucket)
    }
  }
  return rowsByPart
}

export async function listParts(filters: PartsListFilters = {}): Promise<{ items: PartListRow[]; total: number }> {
  await consolidateDuplicatePartMasters().catch(() => 0)

  const page = filters.page ?? 1
  const pageSize = filters.pageSize ?? 80

  const deduped = await listPartMastersLite({ search: filters.search })
  const from = (page - 1) * pageSize
  const pageItems = deduped.slice(from, from + pageSize)
  const bomByPart = await countModelsByPartIds(pageItems.map(p => p.id))
  const items: PartListRow[] = pageItems.map(p => ({
    ...p,
    model_count: partMasterModelCount(p, bomByPart.get(p.id) ?? [])
  }))
  return {
    items,
    total: deduped.length
  }
}

/** Lightweight masters for IPL views — no consolidate / model_count (avoids N× heavy loads). */
export async function listPartMastersLite(filters: { search?: string } = {}): Promise<Part[]> {
  let q = client()
    .from('parts')
    .select('*')
    .eq('is_active', true)
    .order('common_station', { ascending: true, nullsFirst: false })
    .order('common_name', { ascending: true, nullsFirst: false })
    .order('part_name_ar', { ascending: true })
    .limit(5000)

  const search = filters.search?.trim()
  if (search) {
    const esc = search.replace(/%/g, '\\%')
    q = q.or(
      `common_station.ilike.%${esc}%,common_name.ilike.%${esc}%,part_name_ar.ilike.%${esc}%,part_name_en.ilike.%${esc}%,part_number.ilike.%${esc}%`
    )
  }

  const { data, error } = await q
  if (error) throw new Error(error.message)
  return dedupePartListRows((data ?? []) as Part[])
}

