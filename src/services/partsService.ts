export type PartMasterInput = {
  common_station?: string | null
  part_name_ar?: string | null
  part_name_en?: string | null
  common_name?: string | null
  part_type?: string | null
  common_supply_source?: string | null
  /** Used from IPL models tab when removing/assigning models on a part */
  model_names?: string[]
}

function formatApplicableModelsText(names: string[]): string | null {
  const clean = [...new Set(names.map(n => n.trim()).filter(Boolean))]
  return clean.length ? clean.join(', ') : null
}

function buildPartMasterPayload(input: PartMasterInput): Record<string, string | null> {
  const payload: Record<string, string | null> = {
    part_name_ar: trimOrNull(input.part_name_ar),
    part_name_en: trimOrNull(input.part_name_en),
    common_station: trimOrNull(input.common_station),
    common_name: trimOrNull(input.common_name),
    part_type: masterPartType(input),
    common_supply_source: masterSupplySource(input)
  }
  if (input.model_names !== undefined) {
    payload.applicable_models_text = formatApplicableModelsText(input.model_names)
  }
  return payload
}

function trimOrNull(v?: string | null): string | null {
  const s = v?.trim()
  return s || null
}

function masterPartType(input: PartMasterInput): string {
  return effectivePartKind(input.part_type ?? DEFAULT_PART_KIND)
}

function masterSupplySource(input: PartMasterInput): string {
  return effectiveSupplySource(input.common_supply_source ?? DEFAULT_SUPPLY_SOURCE)
}

function partNumberSeed(input: PartMasterInput): string {
  return (
    trimOrNull(input.common_name) ||
    trimOrNull(input.part_name_en) ||
    trimOrNull(input.part_name_ar) ||
    trimOrNull(input.common_station) ||
    ''
  )
}

function generatedPartNumber(seed: string): string {
  const base = normalizePartNumber(seed, { ignoreDashes: false }).replace(/[^A-Z0-9-]/g, '')
  const suffix = Date.now().toString(36).toUpperCase()
  return (base ? base.slice(0, 32) : 'PART') + '-' + suffix
}

export async function createPartMaster(input: PartMasterInput): Promise<{ id: string }> {
  const existing = await findExistingPartMaster(input)
  if (existing) {
    await updatePartMaster(existing.id, {
      ...input,
      common_name: input.common_name?.trim() || existing.common_name || input.part_name_ar
    })
    return { id: existing.id }
  }

  const partNumber = generatedPartNumber(partNumberSeed(input) || 'PART')

  const { data, error } = await client()
    .from('parts')
    .insert({
      part_number: partNumber,
      normalized_part_number: normalizePartNumber(partNumber),
      ...buildPartMasterPayload(input)
    })
    .select('id')
    .single()

  if (error) throw new Error(error.message)
  return { id: data.id as string }
}

export async function updatePartMaster(partId: string, input: PartMasterInput): Promise<void> {
  const { error } = await client()
    .from('parts')
    .update(buildPartMasterPayload(input))
    .eq('id', partId)

  if (error) throw new Error(error.message)
}

export async function deletePart(partId: string): Promise<void> {
  const { error } = await client().from('parts').update({ is_active: false }).eq('id', partId)
  if (error) throw new Error(error.message)
}

async function findExistingPartMaster(input: PartMasterInput): Promise<Part | null> {
  const ar = input.part_name_ar?.trim()
  if (!ar) return null
  const { data, error } = await client()
    .from('parts')
    .select('*')
    .eq('is_active', true)
    .ilike('part_name_ar', ar)
    .limit(20)
  if (error) throw new Error(error.message)
  const target = ar.toLowerCase()
  const matches = ((data ?? []) as Part[]).filter(p => p.part_name_ar?.trim().toLowerCase() === target)
  return matches.length ? pickBestPartMaster(matches) : null
}

function partToMasterHit(part: Part): PartMasterHit {
  return {
    id: part.id,
    part_number: part.part_number,
    part_name_ar: part.part_name_ar,
    part_name_en: part.part_name_en,
    common_name: part.common_name,
    common_station: part.common_station,
    part_type: part.part_type,
    common_supply_source: part.common_supply_source
  }
}

/** Exact Arabic name match in parts master list (optionally excluding one id). */
export async function findPartMasterByArabicName(
  name: string,
  excludeId?: string | null
): Promise<PartMasterHit | null> {
  const existing = await findExistingPartMaster({ part_name_ar: name })
  if (!existing) return null
  if (excludeId && existing.id === excludeId) return null
  return partToMasterHit(existing)
}

/** Merge duplicate master-list rows that share the same Arabic name. */
export async function consolidateDuplicatePartMasters(): Promise<number> {
  const { data, error } = await client().from('parts').select('*').eq('is_active', true).limit(5000)
  if (error) throw new Error(error.message)

  const groups = new Map<string, Part[]>()
  for (const part of (data ?? []) as Part[]) {
    const key = partListMasterKey(part)
    if (key.startsWith('id:')) continue
    const bucket = groups.get(key) ?? []
    bucket.push(part)
    groups.set(key, bucket)
  }

  let removed = 0
  for (const group of groups.values()) {
    if (group.length <= 1) continue
    const canonical = pickBestPartMaster(group)
    for (const dup of group) {
      if (dup.id === canonical.id) continue
      const { error: bomErr } = await client().from('bom_items').update({ part_id: canonical.id }).eq('part_id', dup.id)
      if (bomErr) throw new Error(bomErr.message)
      await deletePart(dup.id)
      removed++
    }
  }
  return removed
}

